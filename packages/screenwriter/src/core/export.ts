/** Generated deliverables: submission package, full script, outline, report. */

import { renderScript } from './script.js'
import type { CheckResult, Project } from './types.js'

const GENERATED = '<!-- generated by duanju; do not edit -->'

function list(items: readonly string[], empty = '（待补）'): string {
  return items.length === 0 ? empty : items.map((item) => `- ${item}`).join('\n')
}

export function submissionMarkdown(project: Project, check?: CheckResult): string {
  const { settings, story, characters, plans, scripts } = project
  const orderedPlans = [...plans.values()].sort((a, b) => a.number - b.number)
  const opening = [1, 2, 3].map((episode) => scripts.get(episode)).filter((script): script is NonNullable<typeof script> => script !== undefined)
  const lines: string[] = [
    GENERATED,
    '',
    '# 投稿包',
    '',
    '## 1. 作品信息',
    '',
    `- 剧名：${settings.title}`,
    `- 平台：${settings.platform}`,
    `- 题材：${settings.genre.join('、')}`,
    `- 受众：${settings.audience}`,
    `- 体量：${String(settings.episodes)} 集 × 约 ${String(settings.secondsPerEpisode)} 秒`,
    `- 单集字数窗口：${String(settings.wordWindow.min)}–${String(settings.wordWindow.max)} 字`,
    `- 成本档：${{ low: '低', medium: '中', high: '高' }[settings.budgetTier]}`,
    '',
    '## 2. 一句话',
    '',
    story.sentence === '' ? '（待补）' : story.sentence,
    '',
    '## 3. 卖点与差异化',
    '',
    list(story.differentiators),
    '',
    '## 4. 人物小传',
    '',
  ]
  if (characters.length === 0) lines.push('（待补）', '')
  for (const character of characters) {
    lines.push(`### ${character.name}（${character.role} / ${character.camp}）`, '')
    lines.push(`- 欲望：${character.desire}`)
    lines.push(`- 痛点：${character.painPoint}`)
    lines.push(`- 性格：${character.personality}`)
    lines.push(`- 说话方式：${character.voice}`)
    lines.push(`- 成长弧：${character.arc}`)
    lines.push(`- 出场：第 ${String(character.firstEpisode)} 集${character.exitEpisode === null ? '' : `；退场：第 ${String(character.exitEpisode)} 集`}`)
    lines.push('')
  }
  lines.push('## 5. 三阶段', '')
  for (const stage of [...story.stages].sort((a, b) => a.from - b.from)) {
    lines.push(`### 第${String(stage.from)}–${String(stage.to)}集：${stage.task}`, '')
    lines.push(`- 阶段目标：${stage.goal}`)
    lines.push(`- 小目标：${stage.miniGoal}`)
    lines.push(`- 信息差：${stage.infoGap}`)
    lines.push('')
  }
  lines.push('## 6. 分集大纲', '')
  if (orderedPlans.length === 0) lines.push('（待补）', '')
  for (const plan of orderedPlans) {
    lines.push(`### 第${String(plan.number)}集 ${plan.title}`.trim(), '')
    lines.push(`- 阶段：${String(plan.stage)}｜情绪点：${plan.emotion}（${plan.size}）｜信息差：${plan.infoGap}`)
    lines.push(`- 目标：${plan.goal}`)
    lines.push(`- 冲突：${plan.conflict}`)
    lines.push(`- 钩子：${plan.hookType}｜${plan.hook}`)
    lines.push('')
  }
  lines.push('## 7. 前三集剧本', '')
  if (opening.length === 0) lines.push('（待补）', '')
  for (const script of opening) {
    lines.push(`### 第${String(script.episode)}集 ${script.title}`.trim(), '', '```text', renderScript(script).trimEnd(), '```', '')
  }
  lines.push('## 8. 检查摘要', '')
  if (check === undefined) {
    lines.push('尚未运行全量机检。建议先运行 `scriptwriter_check scope=all`。', '')
  } else {
    lines.push(`- 规则版本：${check.rulesVersion}`)
    lines.push(`- error ${String(check.counts.error)} / warn ${String(check.counts.warn)} / info ${String(check.counts.info)}`)
    const errors = check.findings.filter((item) => item.severity === 'error').slice(0, 10)
    if (errors.length > 0) {
      lines.push('', '仍需处理：')
      for (const item of errors) lines.push(`- [${item.code}] ${item.message}`)
    }
    lines.push('')
  }
  lines.push('## 9. 待确认事项', '')
  lines.push('- [ ] 作者确认交付版本')
  lines.push('- [ ] 合规与政策风险需人工复核（本包不构成合规结论）')
  lines.push('- [ ] 平台投稿格式与字数以平台最新要求为准')
  lines.push('')
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`
}

export function scriptsMarkdown(project: Project): string {
  const scripts = [...project.scripts.values()].sort((a, b) => a.episode - b.episode)
  const lines: string[] = [GENERATED, '', `# ${project.settings.title} · 全剧剧本`, '']
  for (const script of scripts) {
    lines.push('---', '', renderScript(script).trimEnd(), '')
  }
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`
}

export function outlineMarkdown(project: Project): string {
  const { settings, story } = project
  const plans = [...project.plans.values()].sort((a, b) => a.number - b.number)
  const lines: string[] = [
    GENERATED,
    '',
    `# ${settings.title} · 分集大纲`,
    '',
    `- 体量：${String(settings.episodes)} 集 × 约 ${String(settings.secondsPerEpisode)} 秒`,
    `- 一句话：${story.sentence}`,
    '',
    '## 阶段',
    '',
    '| 阶段 | 集数 | 任务 | 目标 | 小目标 | 信息差 |',
    '|---|---|---|---|---|---|',
  ]
  for (const stage of [...story.stages].sort((a, b) => a.from - b.from)) {
    lines.push(`| ${String(stage.index)} | ${String(stage.from)}–${String(stage.to)} | ${stage.task} | ${stage.goal} | ${stage.miniGoal} | ${stage.infoGap} |`)
  }
  lines.push('', '## 分集', '')
  for (const plan of plans) {
    lines.push(`### 第${String(plan.number)}集 ${plan.title}`.trim(), '')
    lines.push(`- 目标：${plan.goal}`)
    lines.push(`- 冲突：${plan.conflict}`)
    lines.push(`- 情绪点：${plan.emotion}（${plan.size}）`)
    lines.push(`- 信息差：${plan.infoGap}`)
    lines.push(`- 钩子：${plan.hookType}｜${plan.hook}`)
    lines.push(`- 前 30 秒：${plan.open30.background} / ${plan.open30.dilemma} / ${plan.open30.motive}`)
    lines.push(`- 中段：${plan.mid.advance} / ${plan.mid.relation} / ${plan.mid.foreshadow}`)
    lines.push(`- 末 30 秒：${plan.close30}`)
    lines.push('')
  }
  return `${lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd()}\n`
}
